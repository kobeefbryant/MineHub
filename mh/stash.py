"""Stash integration: config bootstrap, scan trigger and bulk tag push via GraphQL."""
from __future__ import annotations

import json
import subprocess
import time
from pathlib import Path
from typing import Any, Iterable

import requests

from .config import DATA, LIBRARY, MEDIA_ROOT, TOOLS
from .db import Ledger

STASH_DIR = TOOLS / "stash"
STASH_EXE = STASH_DIR / "stash-win.exe"
STASH_DB = DATA / "stash" / "stash-go.sqlite"
STASH_GEN = MEDIA_ROOT / "stash" / "generated"
CONFIG = STASH_DIR / "config.yml"
ENDPOINT = "http://127.0.0.1:9998/graphql"

CATEGORY_TAGS = {
    "daily": ("daily", "日常"),
    "sexy": ("sexy", "性感"),
    "adult": ("adult", "成人"),
    "anime": ("anime", "二次元"),
    "sticker": ("sticker", "表情包"),
    "screenshot": ("screenshot", "截图"),
    "review": ("review", "待复核"),
    "other": ("other", "其他"),
}
LEVEL_TAGS = {"safe": ("sfw", "安全"), "suggestive": ("suggestive", "擦边"), "explicit": ("explicit", "露骨")}


def ensure_config() -> Path:
    if CONFIG.exists():
        return CONFIG
    (DATA / "stash").mkdir(parents=True, exist_ok=True)
    STASH_GEN.mkdir(parents=True, exist_ok=True)
    cfg = f"""# Generated by MineHub
database: {STASH_DB.as_posix()}
generated: {STASH_GEN.as_posix()}
stash:
  paths:
    - {LIBRARY.as_posix()}
blobs_path: {(MEDIA_ROOT / 'stash' / 'blobs').as_posix()}
store_blobs: false
ffmpeg: D:/ffmpeg/bin/ffmpeg.exe
ffprobe: D:/ffmpeg/bin/ffprobe.exe
log_level: Info
log_out: {(DATA / 'logs' / 'stash.log').as_posix()}
"""
    CONFIG.write_text(cfg, encoding="utf-8")
    return CONFIG


class Stash:
    def __init__(self, endpoint: str = ENDPOINT) -> None:
        self.endpoint = endpoint
        self.session = requests.Session()

    def graphql(self, query: str, variables: dict | None = None) -> dict:
        r = self.session.post(self.endpoint, json={"query": query, "variables": variables or {}}, timeout=120)
        r.raise_for_status()
        data = r.json()
        if data.get("errors"):
            raise RuntimeError(f"stash graphql error: {data['errors'][:2]}")
        return data["data"]

    def image_paths(self, image_id: str) -> list[str]:
        data = self.graphql(
            "query($id:ID!){ findImage(id:$id){ visual_files{ ... on ImageFile { path } ... on VideoFile { path } } } }",
            {"id": str(image_id)},
        )
        files = (data.get("findImage") or {}).get("visual_files") or []
        return [str(f["path"]) for f in files if f.get("path")]

    def image_path(self, image_id: str) -> str | None:
        paths = self.image_paths(image_id)
        return paths[0] if paths else None

    def scene_paths(self, scene_id: str) -> list[str]:
        data = self.graphql(
            "query($id:ID!){ findScene(id:$id){ files{ path } } }",
            {"id": str(scene_id)},
        )
        files = (data.get("findScene") or {}).get("files") or []
        return [str(f["path"]) for f in files if f.get("path")]

    def destroy_image(self, image_id: str, delete_file: bool) -> None:
        self.graphql(
            "mutation($id:ID!,$file:Boolean){ imageDestroy(input:{id:$id,delete_file:$file,delete_generated:true,destroy_file_entry:true}) }",
            {"id": str(image_id), "file": bool(delete_file)},
        )

    def destroy_scene(self, scene_id: str, delete_file: bool) -> None:
        self.graphql(
            "mutation($id:ID!,$file:Boolean){ sceneDestroy(input:{id:$id,delete_file:$file,delete_generated:true,destroy_file_entry:true}) }",
            {"id": str(scene_id), "file": bool(delete_file)},
        )

    def wait_ready(self, timeout: float = 180) -> bool:
        deadline = time.time() + timeout
        while time.time() < deadline:
            try:
                self.graphql("{ systemStatus { status } }")
                return True
            except Exception:
                time.sleep(3)
        return False

    def install_ui_plugin(self, path: Path | str = STASH_DIR / "custom_minehub.js") -> dict:
        plugin_dir = STASH_DIR / "plugins" / "minehub"
        plugin_dir.mkdir(parents=True, exist_ok=True)
        (plugin_dir / "custom_minehub.js").write_text(Path(path).read_text(encoding="utf-8"), encoding="utf-8")
        (plugin_dir / "minehub.yml").write_text(
            """name: MineHub Native Search
description: MineHub media intelligence for Stash: semantic image/text search, duplicate detection, native preview, and optional QQ cache import.
version: 1.0.5
ui:
  javascript:
    - custom_minehub.js
""",
            encoding="utf-8",
        )
        self.graphql("mutation { reloadPlugins }")
        return self.graphql(
            "mutation { configureInterface(input:{javascript:\"\", javascriptEnabled:true}) { __typename } }"
        )

    # ---- scan -------------------------------------------------------
    def scan(self, paths: Iterable[str] = ()) -> str:
        paths = [p for p in paths] or [LIBRARY.as_posix()]
        return self.graphql(
            """mutation($paths:[String!]!){ metadataScan(input:{paths:$paths, scanGenerateCovers:true,
                scanGeneratePreviews:false, scanGenerateImagePreviews:false, scanGenerateSprites:false,
                scanGeneratePhashes:false, scanGenerateThumbnails:true, scanGenerateClipPreviews:false}) }""",
            {"paths": paths},
        )["metadataScan"]

    def wait_job(self, job_id: str, timeout: float = 6 * 3600, poll: float = 10) -> str:
        deadline = time.time() + timeout
        status = "UNKNOWN"
        while time.time() < deadline:
            try:
                st = self.graphql(
                    "query($id:ID!){ findJob(input:{id:$id}){ status progress description } }", {"id": job_id}
                )["findJob"]
                status = st["status"]
                if status not in ("READY", "RUNNING"):
                    return status
            except Exception:
                pass
            time.sleep(poll)
        return status

    def job_status(self) -> list[dict]:
        d = self.graphql("{ jobQueue { id description status progress } }")
        return d["jobQueue"]

    # ---- tags -------------------------------------------------------
    def tag_id(self, name: str, cache: dict[str, str]) -> str:
        if name in cache:
            return cache[name]
        found = self.graphql(
            "query($n:String!){ findTags(tag_filter:{name:{value:$n, modifier:EQUALS}}, filter:{per_page:1}){ tags{ id name } } }",
            {"n": name},
        )["findTags"]["tags"]
        if found:
            cache[name] = found[0]["id"]
            return cache[name]
        created = self.graphql("mutation($n:String!){ tagCreate(input:{name:$n}){ id } }", {"n": name})
        cache[name] = created["tagCreate"]["id"]
        return cache[name]

    def _bulk(self, kind: str, ids: list[str], tag_ids: list[str]) -> None:
        mut = "bulkSceneUpdate" if kind == "scene" else "bulkImageUpdate"
        self.graphql(
            f"mutation($ids:[ID!]!,$t:[ID!]!){{ {mut}(input:{{ids:$ids, tag_ids:{{ids:$t, mode:ADD}}}}){{ id }} }}",
            {"ids": ids, "t": tag_ids},
        )

    def _all_objects(self, kind: str) -> list[dict]:
        out: list[dict] = []
        page = 1
        seen = 0
        field = "findScenes" if kind == "scene" else "findImages"
        sub = "scenes" if kind == "scene" else "images"
        if kind == "scene":
            files_sel = "files{ path }"
            files_key = "files"
        else:
            # Stash may classify GIF/APNG (and some odd JPEGs) as VideoFile,
            # which are exposed through visual_files rather than files.
            files_sel = "visual_files{ ... on ImageFile{ path } ... on VideoFile{ path } }"
            files_key = "visual_files"
        while True:
            d = self.graphql(
                f"""query($p:Int!){{ {field}(filter:{{page:$p, per_page:500}}){{ count {sub}{{ id {files_sel} }} }} }}""",
                {"p": page},
            )[field]
            batch = d[sub]
            if not batch:
                break
            seen += len(batch)
            for o in batch:
                for f in o.get(files_key, []):
                    if f.get("path"):
                        out.append({"id": o["id"], "path": f["path"]})
            if seen >= d["count"]:
                break
            page += 1
        return out

    def push_tags(self, only_pending: bool = True) -> dict:
        led = Ledger()
        q = "SELECT * FROM files WHERE final_json IS NOT NULL AND move_state='moved'"
        if only_pending:
            q += " AND stash_state='pending'"
        rows = led.conn.execute(q).fetchall()
        if not rows:
            led.close()
            return {"tagged": 0}

        path_map: dict[str, tuple[str, str]] = {}
        for kind in ("scene", "image"):
            for obj in self._all_objects(kind):
                path_map[Path(obj["path"]).resolve().as_posix().lower()] = (kind, obj["id"])

        cache: dict[str, str] = {}
        buckets: dict[str, list[tuple[str, str]]] = {}
        matched_ids: list[int] = []
        matched = 0
        for r in rows:
            key = Path(r["target_path"]).resolve().as_posix().lower() if r["target_path"] else ""
            hit = path_map.get(key)
            if not hit:
                continue
            matched += 1
            matched_ids.append(r["id"])
            kind, sid = hit
            final = json.loads(r["final_json"])
            names: list[str] = []
            cat = final.get("category") or r["category"]
            if cat in CATEGORY_TAGS:
                names.extend(CATEGORY_TAGS[cat])
            lvl = final.get("nsfw_level")
            if lvl in LEVEL_TAGS:
                names.extend(LEVEL_TAGS[lvl])
            names.extend(final.get("tags") or [])
            names.append("qq")
            for n in dict.fromkeys(x.strip() for x in names if x and len(x) <= 40):
                buckets.setdefault(n, []).append((kind, sid))

        for name, items in buckets.items():
            tid = self.tag_id(name, cache)
            for kind in ("scene", "image"):
                ids = [sid for k, sid in items if k == kind]
                for i in range(0, len(ids), 500):
                    self._bulk(kind, ids[i:i + 500], [tid])
        for i in range(0, len(matched_ids), 2000):
            chunk = matched_ids[i:i + 2000]
            led.conn.execute(
                f"UPDATE files SET stash_state='tagged' WHERE id IN ({','.join('?' * len(chunk))})", chunk
            )
        led.conn.commit()
        led.close()
        return {"tagged": matched, "tags": len(buckets), "unmatched": len(rows) - matched}


def start_stash(port: int = 9998) -> subprocess.Popen:
    ensure_config()
    log = open(DATA / "logs" / "stash_stdout.log", "a", encoding="utf-8", errors="replace")
    return subprocess.Popen(
        [str(STASH_EXE), "--config", str(CONFIG), "--port", str(port), "--host", "127.0.0.1"],
        stdout=log, stderr=subprocess.STDOUT, cwd=str(STASH_DIR),
    )